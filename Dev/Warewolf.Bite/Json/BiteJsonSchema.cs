using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text.Json;
using System.Text.Json.Nodes;
using Dev2;
using Warewolf.Bite.Xaml;

namespace Warewolf.Bite.Json
{
    /// <summary>
    /// Generates the JSON Schema (draft 2020-12) for the version 1 JSON body (WF removal T3.1) from the same rules
    /// <see cref="BiteJsonWriter"/> and <see cref="BiteJsonReader"/> follow, so it cannot drift from them: every
    /// activity a .bite can hold, and every type its definition members (<see cref="DefinitionMembers"/>) reach.
    /// docs/BiteDefinition-v1.schema.json is the checked-in output; a test keeps it current.
    /// </summary>
    public static class BiteJsonSchema
    {
        public const string Id = "https://warewolf.io/schemas/bite-definition-v1.json";

        // "\n" on every OS, so the checked-in copy is byte-identical wherever it is regenerated.
        static readonly JsonWriterOptions WriterOptions = new JsonWriterOptions { Indented = true, NewLine = "\n" };

        public static string Generate()
        {
            using (var stream = new MemoryStream())
            {
                using (var writer = new Utf8JsonWriter(stream, WriterOptions))
                {
                    new Generator().Build().WriteTo(writer);
                }
                return System.Text.Encoding.UTF8.GetString(stream.ToArray());
            }
        }

        sealed class Generator
        {
            readonly List<Type> _candidates = WarewolfTypes();
            readonly SortedDictionary<string, JsonNode> _definitions = new SortedDictionary<string, JsonNode>(StringComparer.Ordinal);
            readonly Queue<Type> _pending = new Queue<Type>();
            readonly HashSet<Type> _queued = new HashSet<Type>();

            public JsonObject Build()
            {
                var activities = Implementations(typeof(IDev2Activity));
                var activity = new JsonObject { ["anyOf"] = new JsonArray(activities.Select(Ref).ToArray<JsonNode?>()) };
                while (_pending.Count > 0)
                {
                    var type = _pending.Dequeue();
                    _definitions[type.FullName!] = ObjectSchema(type);
                }

                var definitions = new JsonObject
                {
                    ["activity"] = activity,
                    ["expressionArgument"] = new JsonObject
                    {
                        ["description"] = "A WF argument holding an expression, kept as text and never compiled ({\"$expr\": \"...\"}), or nothing ({}).",
                        ["type"] = "object",
                        ["properties"] = new JsonObject { ["$expr"] = new JsonObject { ["type"] = "string" } },
                        ["additionalProperties"] = false,
                    },
                    ["nodeId"] = Nullable(new JsonObject { ["type"] = "string" }),
                    ["node"] = new JsonObject
                    {
                        ["oneOf"] = new JsonArray(
                            Node("step", ("activity", Nullable(ActivityRef())), ("next", NodeIdRef())),
                            Node("decision", ("displayName", Nullable(new JsonObject { ["type"] = "string" })), ("condition", Nullable(ActivityRef())), ("true", NodeIdRef()), ("false", NodeIdRef())),
                            Node("switch", ("displayName", Nullable(new JsonObject { ["type"] = "string" })), ("expression", Nullable(ActivityRef())),
                                ("cases", new JsonObject { ["type"] = "object", ["additionalProperties"] = NodeIdRef() }), ("default", NodeIdRef()))),
                    },
                };
                foreach (var (name, schema) in _definitions)
                {
                    definitions[name] = schema;
                }

                return new JsonObject
                {
                    ["$schema"] = "https://json-schema.org/draft/2020-12/schema",
                    ["$id"] = Id,
                    ["title"] = "Warewolf BiteDefinition, format version 1",
                    ["description"] = "The JSON body of a .bite workflow resource (<BiteDefinition FormatVersion=\"1\">). Generated by Warewolf.Bite.Json.BiteJsonSchema; see docs/BiteDefinition-Format.md.",
                    ["type"] = "object",
                    ["properties"] = new JsonObject
                    {
                        ["name"] = Nullable(new JsonObject { ["type"] = "string" }),
                        ["start"] = NodeIdRef(),
                        ["nodes"] = new JsonObject { ["type"] = "object", ["additionalProperties"] = new JsonObject { ["$ref"] = "#/$defs/node" } },
                        ["layout"] = new JsonObject
                        {
                            ["type"] = "object",
                            ["additionalProperties"] = new JsonObject
                            {
                                ["type"] = "object",
                                ["properties"] = new JsonObject { ["x"] = new JsonObject { ["type"] = "number" }, ["y"] = new JsonObject { ["type"] = "number" } },
                            },
                        },
                    },
                    ["required"] = new JsonArray("start", "nodes"),
                    ["additionalProperties"] = false,
                    ["$defs"] = definitions,
                };
            }

            static JsonObject Node(string kind, params (string Name, JsonNode Schema)[] members)
            {
                var properties = new JsonObject { ["kind"] = new JsonObject { ["const"] = kind } };
                foreach (var (name, schema) in members)
                {
                    properties[name] = schema;
                }
                return new JsonObject
                {
                    ["type"] = "object",
                    ["properties"] = properties,
                    ["required"] = new JsonArray("kind"),
                    ["additionalProperties"] = false,
                };
            }

            JsonObject ObjectSchema(Type type)
            {
                var properties = new JsonObject { ["$type"] = new JsonObject { ["const"] = type.FullName } };
                foreach (var member in DefinitionMembers.Of(type))
                {
                    properties[member.Name] = ValueSchema(member.PropertyType);
                }
                return new JsonObject
                {
                    ["type"] = "object",
                    ["properties"] = properties,
                    ["required"] = new JsonArray("$type"),
                    ["additionalProperties"] = false,
                };
            }

            // The JSON a value of the declared type is written as (see the Values table in docs/BiteDefinition-Format.md).
            JsonNode ValueSchema(Type declared)
            {
                var underlying = System.Nullable.GetUnderlyingType(declared);
                if (underlying != null)
                {
                    return Nullable(ValueSchema(underlying));
                }
                if (declared == typeof(string) || declared == typeof(char) || declared == typeof(Uri) || declared == typeof(TimeSpan))
                {
                    return Nullable(new JsonObject { ["type"] = "string" });
                }
                if (declared == typeof(bool))
                {
                    return new JsonObject { ["type"] = "boolean" };
                }
                if (declared == typeof(byte) || declared == typeof(sbyte) || declared == typeof(short) || declared == typeof(ushort)
                    || declared == typeof(int) || declared == typeof(uint) || declared == typeof(long) || declared == typeof(ulong))
                {
                    return new JsonObject { ["type"] = "integer" };
                }
                if (declared == typeof(float) || declared == typeof(double) || declared == typeof(decimal))
                {
                    return new JsonObject { ["type"] = "number" };
                }
                if (declared.IsEnum)
                {
                    // A [Flags] value is written as "A, B", which no enum list can name.
                    return declared.IsDefined(typeof(FlagsAttribute), false)
                        ? new JsonObject { ["type"] = "string" }
                        : new JsonObject { ["enum"] = new JsonArray(Enum.GetNames(declared).Select(n => (JsonNode?)n).ToArray()) };
                }
                if (declared == typeof(Guid))
                {
                    return new JsonObject { ["type"] = "string", ["format"] = "uuid" };
                }
                if (declared == typeof(DateTime))
                {
                    return new JsonObject { ["type"] = "string", ["format"] = "date-time" };
                }
                if (declared == typeof(Type))
                {
                    return Nullable(new JsonObject { ["type"] = "string", ["description"] = "A full CLR type name, resolved through the allowlist" });
                }
                if (declared == typeof(object))
                {
                    return new JsonObject();
                }
                if (WfArguments.IsArgumentType(declared))
                {
                    return Nullable(ArgumentSchema(declared));
                }
                if (WfArguments.IsDelegateType(declared))
                {
                    return Nullable(new JsonObject
                    {
                        ["type"] = "object",
                        ["properties"] = new JsonObject
                        {
                            ["argument"] = Nullable(new JsonObject { ["type"] = "string" }),
                            ["body"] = Nullable(ActivityRef()),
                        },
                        ["additionalProperties"] = false,
                    });
                }
                if (DefinitionMembers.IsDictionary(declared))
                {
                    var valueType = declared.GetInterfaces().Append(declared)
                        .FirstOrDefault(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IDictionary<,>))?.GetGenericArguments()[1] ?? typeof(object);
                    return Nullable(new JsonObject { ["type"] = "object", ["additionalProperties"] = ValueSchema(valueType) });
                }
                if (declared.IsArray || DefinitionMembers.IsCollection(declared))
                {
                    var itemType = declared.IsArray ? declared.GetElementType()! : DefinitionMembers.ItemType(declared);
                    return Nullable(new JsonObject { ["type"] = "array", ["items"] = ValueSchema(itemType) });
                }

                // An object: any instantiable Warewolf type of the declared type, named by $type. A choice of several is
                // defined once ("anyOf:<declared type>") and referenced, or the activity unions alone would repeat 113 entries
                // at every activity-typed member.
                var implementations = Implementations(declared);
                if (implementations.Count == 0)
                {
                    return new JsonObject { ["type"] = "null" };
                }
                if (implementations.Count == 1)
                {
                    return Nullable(Ref(implementations[0]));
                }
                var union = "anyOf:" + declared.FullName;
                if (!_definitions.ContainsKey(union))
                {
                    _definitions[union] = new JsonObject { ["anyOf"] = new JsonArray(implementations.Select(Ref).ToArray<JsonNode?>()) };
                }
                return Nullable(new JsonObject { ["$ref"] = "#/$defs/" + union });
            }

            // An argument is a literal (InArgument only), {"$expr": "..."}, or {}; Out/InOut hold an expression or nothing.
            JsonObject ArgumentSchema(Type argumentType) =>
                argumentType.GetGenericTypeDefinition().Name.StartsWith("InArgument", StringComparison.Ordinal)
                    ? new JsonObject { ["anyOf"] = new JsonArray(ValueSchema(argumentType.GetGenericArguments()[0]), new JsonObject { ["$ref"] = "#/$defs/expressionArgument" }) }
                    : new JsonObject { ["$ref"] = "#/$defs/expressionArgument" };

            List<Type> Implementations(Type declared)
            {
                var implementations = _candidates.Where(declared.IsAssignableFrom).ToList();
                foreach (var type in implementations.Where(_queued.Add))
                {
                    _pending.Enqueue(type);
                }
                return implementations;
            }

            static JsonNode Ref(Type type) => new JsonObject { ["$ref"] = $"#/$defs/{type.FullName}" };

            static JsonNode ActivityRef() => new JsonObject { ["$ref"] = "#/$defs/activity" };

            static JsonNode NodeIdRef() => new JsonObject { ["$ref"] = "#/$defs/nodeId" };

            static JsonNode Nullable(JsonNode schema)
            {
                if (schema is JsonObject o && o["type"] is JsonValue type && type.GetValueKind() == JsonValueKind.String)
                {
                    return CloneWithType(o, new JsonArray((string)type!, "null"));
                }
                if (schema is JsonObject { Count: 1 } choice && choice["anyOf"] is JsonArray choices)
                {
                    choices.Add(new JsonObject { ["type"] = "null" });
                    return choice;
                }
                return new JsonObject { ["anyOf"] = new JsonArray(schema, new JsonObject { ["type"] = "null" }) };
            }

            static JsonObject CloneWithType(JsonObject schema, JsonArray types)
            {
                var copy = new JsonObject();
                foreach (var (name, value) in schema)
                {
                    copy[name] = name == "type" ? types : value?.DeepClone();
                }
                return copy;
            }

            // What a $type may name: public, concrete Warewolf types the reader can construct, in ordinal name order.
            // Only the assemblies Dev2.Activities references are scanned, so the result does not depend on whatever
            // else the host process happens to have loaded.
            static List<Type> WarewolfTypes()
            {
                var types = new List<Type>();
                var pending = new Queue<Assembly>(new[] { typeof(Unlimited.Applications.BusinessDesignStudio.Activities.DsfCommentActivity).Assembly });
                var seen = new HashSet<string>(StringComparer.Ordinal);
                while (pending.Count > 0)
                {
                    var assembly = pending.Dequeue();
                    if (!seen.Add(assembly.GetName().Name ?? ""))
                    {
                        continue;
                    }
                    types.AddRange(ExportedTypes(assembly).Where(IsConstructible));
                    foreach (var reference in assembly.GetReferencedAssemblies().Where(r => DefinitionMembers.IsWarewolfName(r.Name) && !seen.Contains(r.Name!)))
                    {
                        try
                        {
                            pending.Enqueue(Assembly.Load(reference));
                        }
                        catch (Exception e) when (e is FileNotFoundException or FileLoadException)
                        {
                            // Not deployed alongside; nothing in it can be read either.
                        }
                    }
                }
                return types.OrderBy(t => t.FullName, StringComparer.Ordinal).ToList();
            }

            static IEnumerable<Type> ExportedTypes(Assembly assembly)
            {
                try
                {
                    return assembly.GetExportedTypes();
                }
                catch (ReflectionTypeLoadException e)
                {
                    return e.Types.Where(t => t is { IsPublic: true })!;
                }
            }

            static bool IsConstructible(Type type) =>
                type.IsClass && !type.IsAbstract && !type.ContainsGenericParameters && type.FullName != null
                && type.GetConstructor(Type.EmptyTypes) != null;
        }
    }
}
