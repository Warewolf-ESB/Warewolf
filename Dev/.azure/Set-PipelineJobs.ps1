<#
.SYNOPSIS
    Generates a trimmed-down Dev\.azure\pipeline.yml that only runs the Test-stage jobs you name,
    instead of manually copy-pasting pipeline-TEMPLATE.yml and hand-editing job blocks.

.DESCRIPTION
    Warewolf's Dev\.azure\pipeline.yml defines a Compile stage, a Test stage with ~90 selectable
    jobs, and a Compile_Release stage. When validating a work-in-progress branch, devs often want
    CI to run only a handful of those Test jobs instead of the full suite.

    This script:
      - Reads the full/canonical pipeline.yml from git (HEAD by default) so the list of
        selectable jobs is always complete, even if the on-disk pipeline.yml is currently reduced.
      - Rewrites Dev\.azure\pipeline.yml so the Test stage contains only the jobs you asked for.
        The Compile and Compile_Release stages are always kept as-is (Compile_Release is already
        gated by an IsMainBranch condition, so it's a no-op on feature branches).
      - Backs up whatever pipeline.yml currently contains before writing, so you can restore it.
      - Can list the available job names, list backups, restore a backup, or preview (-DryRun).

.PARAMETER Jobs
    One or more Test-stage job names to keep (e.g. Unit_Tests, Activities_Tests). Case-insensitive.

.PARAMETER ListJobs
    Prints every selectable Test-stage job name (plus the stages that are always kept), then exits.

.PARAMETER ListBackups
    Prints available backups (most recent first), then exits.

.PARAMETER Restore
    Restores pipeline.yml from the most recent backup, or from -BackupFile if given.

.PARAMETER BackupFile
    Backup file name (as shown by -ListBackups) to restore. Only used with -Restore.

.PARAMETER MasterRef
    Git ref to read the canonical/full pipeline.yml from. Defaults to HEAD.

.PARAMETER DryRun
    Prints the pipeline.yml that would be written, without writing it or creating a backup.

.PARAMETER Force
    Skips the confirmation prompt before overwriting pipeline.yml.

.EXAMPLE
    Dev\.azure\Set-PipelineJobs.ps1 -ListJobs

.EXAMPLE
    Dev\.azure\Set-PipelineJobs.ps1 -Jobs Unit_Tests,Activities_Tests

.EXAMPLE
    Dev\.azure\Set-PipelineJobs.ps1 -Restore

.EXAMPLE
    Dev\.azure\Set-PipelineJobs.ps1 -ListBackups
#>
[CmdletBinding(DefaultParameterSetName = 'Generate')]
param(
    [Parameter(ParameterSetName = 'Generate')]
    [string[]]$Jobs,

    [Parameter(ParameterSetName = 'ListJobs')]
    [switch]$ListJobs,

    [Parameter(ParameterSetName = 'ListBackups')]
    [switch]$ListBackups,

    [Parameter(ParameterSetName = 'Restore')]
    [switch]$Restore,

    [Parameter(ParameterSetName = 'Restore')]
    [string]$BackupFile,

    [Parameter(ParameterSetName = 'Generate')]
    [string]$MasterRef = 'HEAD',

    [Parameter(ParameterSetName = 'Generate')]
    [switch]$DryRun,

    [Parameter(ParameterSetName = 'Generate')]
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

$ScriptDir     = $PSScriptRoot
$PipelinePath  = Join-Path $ScriptDir 'pipeline.yml'
$BackupDir     = Join-Path $ScriptDir '.pipeline-backups'
$RepoRelPath   = 'Dev/.azure/pipeline.yml'
$Newline       = "`r`n"

function Get-RepoRoot {
    $root = git -C $ScriptDir rev-parse --show-toplevel 2>$null
    if ($LASTEXITCODE -ne 0 -or -not $root) {
        return $null
    }
    return $root.Trim()
}

function Get-MasterPipelineLines {
    param([string]$Ref)

    $repoRoot = Get-RepoRoot
    if ($repoRoot) {
        $content = git -C $repoRoot show "${Ref}:${RepoRelPath}" 2>$null
        if ($LASTEXITCODE -eq 0 -and $content) {
            Write-Verbose "Using canonical pipeline.yml from git ref '$Ref'."
            return ($content -join $Newline) -split "`r?`n"
        }
        Write-Warning "Could not read '$RepoRelPath' from git ref '$Ref'. Falling back to the on-disk pipeline.yml."
    }
    else {
        Write-Warning "Not inside a git repository (or git is unavailable). Falling back to the on-disk pipeline.yml."
    }

    if (-not (Test-Path $PipelinePath)) {
        throw "No pipeline.yml found on disk at '$PipelinePath' and no git fallback available."
    }
    Write-Warning "The on-disk pipeline.yml may already be a reduced version generated by this script."
    return (Get-Content -Raw $PipelinePath) -split "`r?`n"
}

function Get-Stages {
    param([string[]]$Lines)

    $stageMatches = @()
    for ($i = 0; $i -lt $Lines.Count; $i++) {
        if ($Lines[$i] -match '^- stage:\s*(\S+)') {
            $stageMatches += [PSCustomObject]@{ Name = $Matches[1]; Index = $i }
        }
    }

    $preambleEnd = if ($stageMatches.Count -gt 0) { $stageMatches[0].Index } else { $Lines.Count }
    $preamble = if ($preambleEnd -gt 0) { $Lines[0..($preambleEnd - 1)] } else { @() }

    $stages = @()
    for ($s = 0; $s -lt $stageMatches.Count; $s++) {
        $start = $stageMatches[$s].Index
        $end = if ($s + 1 -lt $stageMatches.Count) { $stageMatches[$s + 1].Index } else { $Lines.Count }
        $stages += [PSCustomObject]@{
            Name  = $stageMatches[$s].Name
            Lines = $Lines[$start..($end - 1)]
        }
    }

    return [PSCustomObject]@{ Preamble = $preamble; Stages = $stages }
}

function Get-JobsInStage {
    param([string[]]$StageLines)

    $jobMatches = @()
    for ($i = 0; $i -lt $StageLines.Count; $i++) {
        if ($StageLines[$i] -match '^  - job:\s*(\S+)') {
            $jobMatches += [PSCustomObject]@{ Name = $Matches[1]; Index = $i }
        }
    }

    $headerEnd = if ($jobMatches.Count -gt 0) { $jobMatches[0].Index } else { $StageLines.Count }
    $header = if ($headerEnd -gt 0) { $StageLines[0..($headerEnd - 1)] } else { @() }

    $jobs = [ordered]@{}
    for ($j = 0; $j -lt $jobMatches.Count; $j++) {
        $start = $jobMatches[$j].Index
        $end = if ($j + 1 -lt $jobMatches.Count) { $jobMatches[$j + 1].Index } else { $StageLines.Count }
        $jobs[$jobMatches[$j].Name] = $StageLines[$start..($end - 1)]
    }

    return [PSCustomObject]@{ Header = $header; Jobs = $jobs }
}

function Get-TrimmedMergeCoverageLines {
    param([string[]]$JobLines, [string[]]$SelectedJobs)

    $keep = $SelectedJobs | Where-Object { $_ -ne 'MergeCoverage' }
    $out = New-Object System.Collections.Generic.List[string]
    $inDependsOn = $false
    $removed = @()

    foreach ($line in $JobLines) {
        if ($line -match '^\s{4}dependsOn:\s*$') {
            $inDependsOn = $true
            $out.Add($line)
            continue
        }
        if ($inDependsOn) {
            if ($line -match '^\s{6}-\s*(\S+)\s*$') {
                $depName = $Matches[1]
                if ($keep -contains $depName) {
                    $out.Add($line)
                }
                else {
                    $removed += $depName
                }
                continue
            }
            else {
                $inDependsOn = $false
            }
        }
        $out.Add($line)
    }

    return [PSCustomObject]@{ Lines = $out.ToArray(); Removed = $removed }
}

function Get-Suggestions {
    param([string]$Name, [string[]]$Candidates)

    $lowerName = $Name.ToLowerInvariant()
    $matches = $Candidates | Where-Object { $_.ToLowerInvariant().Contains($lowerName) -or $lowerName.Contains($_.ToLowerInvariant()) }
    if (-not $matches) {
        # Fall back to a crude "starts with same letters" heuristic.
        $prefix = $lowerName.Substring(0, [Math]::Min(3, $lowerName.Length))
        $matches = $Candidates | Where-Object { $_.ToLowerInvariant().StartsWith($prefix) }
    }
    return $matches | Select-Object -First 5
}

function Backup-CurrentPipeline {
    param([string]$Reason)

    if (-not (Test-Path $PipelinePath)) {
        Write-Warning "No existing pipeline.yml to back up."
        return $null
    }

    New-Item -ItemType Directory -Force -Path $BackupDir | Out-Null
    $timestamp = Get-Date -Format 'yyyyMMdd-HHmmss'
    $destName = "pipeline_$timestamp.yml"
    $destPath = Join-Path $BackupDir $destName
    if (Test-Path $destPath) {
        # Extremely unlikely (same second), but guarantee uniqueness anyway.
        $destName = "pipeline_$timestamp-$([guid]::NewGuid().ToString('N').Substring(0,6)).yml"
        $destPath = Join-Path $BackupDir $destName
    }
    Copy-Item -Path $PipelinePath -Destination $destPath
    Write-Host "Backed up current pipeline.yml ($Reason) -> .pipeline-backups\$destName"
    return $destPath
}

# ---------------------------------------------------------------------------
# -ListBackups
# ---------------------------------------------------------------------------
if ($ListBackups) {
    if (-not (Test-Path $BackupDir)) {
        Write-Host "No backups yet. Run with -Jobs to generate a pipeline.yml (this creates a backup first)."
        return
    }
    $backups = Get-ChildItem $BackupDir -Filter 'pipeline_*.yml' | Sort-Object LastWriteTime -Descending
    if (-not $backups) {
        Write-Host "No backups yet."
        return
    }
    Write-Host "Available backups (most recent first):"
    foreach ($b in $backups) {
        Write-Host ("  {0}  {1,10:N0} bytes  {2}" -f $b.Name, $b.Length, $b.LastWriteTime)
    }
    return
}

# ---------------------------------------------------------------------------
# -Restore
# ---------------------------------------------------------------------------
if ($Restore) {
    if (-not (Test-Path $BackupDir)) {
        throw "No backups directory found at '$BackupDir'. Nothing to restore."
    }

    if ($BackupFile) {
        $srcPath = Join-Path $BackupDir $BackupFile
        if (-not (Test-Path $srcPath)) {
            throw "Backup file '$BackupFile' not found in '$BackupDir'. Run -ListBackups to see available backups."
        }
    }
    else {
        $latest = Get-ChildItem $BackupDir -Filter 'pipeline_*.yml' | Sort-Object LastWriteTime -Descending | Select-Object -First 1
        if (-not $latest) {
            throw "No backups found in '$BackupDir'."
        }
        $srcPath = $latest.FullName
    }

    Write-Host "Restoring pipeline.yml from: $(Split-Path -Leaf $srcPath)"
    Backup-CurrentPipeline -Reason 'pre-restore' | Out-Null
    Copy-Item -Path $srcPath -Destination $PipelinePath -Force
    Write-Host "Restore complete. pipeline.yml now matches '$(Split-Path -Leaf $srcPath)'."
    Write-Host "(Your pre-restore pipeline.yml was itself backed up, so this can be undone too.)"
    return
}

# ---------------------------------------------------------------------------
# -ListJobs
# ---------------------------------------------------------------------------
if ($ListJobs) {
    $masterLines = Get-MasterPipelineLines -Ref $MasterRef
    $parsed = Get-Stages -Lines $masterLines

    foreach ($stage in $parsed.Stages) {
        if ($stage.Name -eq 'Test') {
            $testJobs = Get-JobsInStage -StageLines $stage.Lines
            Write-Host "Test stage (selectable via -Jobs):"
            foreach ($name in $testJobs.Jobs.Keys) {
                Write-Host "  - $name"
            }
        }
        else {
            Write-Host "$($stage.Name) stage: always kept as-is"
        }
    }
    return
}

# ---------------------------------------------------------------------------
# Default: -Jobs (generate)
# ---------------------------------------------------------------------------
if (-not $Jobs -or $Jobs.Count -eq 0) {
    Write-Host "Usage:"
    Write-Host "  Set-PipelineJobs.ps1 -Jobs <job1>,<job2>,...   # generate a trimmed pipeline.yml"
    Write-Host "  Set-PipelineJobs.ps1 -ListJobs                 # list selectable job names"
    Write-Host "  Set-PipelineJobs.ps1 -ListBackups               # list available backups"
    Write-Host "  Set-PipelineJobs.ps1 -Restore [-BackupFile x]   # restore a backup"
    return
}

$masterLines = Get-MasterPipelineLines -Ref $MasterRef
$parsedMaster = Get-Stages -Lines $masterLines

$testStage = $parsedMaster.Stages | Where-Object { $_.Name -eq 'Test' }
if (-not $testStage) {
    throw "Could not find a 'Test' stage in the canonical pipeline.yml (ref '$MasterRef')."
}
$testParsed = Get-JobsInStage -StageLines $testStage.Lines
$availableJobNames = @($testParsed.Jobs.Keys)

# Resolve requested names case-insensitively and de-duplicate, keeping canonical casing.
$resolvedNames = New-Object System.Collections.Generic.List[string]
$unknownNames = @()
foreach ($requested in $Jobs) {
    $match = $availableJobNames | Where-Object { $_ -ieq $requested } | Select-Object -First 1
    if ($match) {
        if (-not $resolvedNames.Contains($match)) {
            $resolvedNames.Add($match)
        }
    }
    else {
        $unknownNames += $requested
    }
}

if ($unknownNames.Count -gt 0) {
    Write-Host "Unknown job name(s):" -ForegroundColor Red
    foreach ($u in $unknownNames) {
        $suggestions = Get-Suggestions -Name $u -Candidates $availableJobNames
        if ($suggestions) {
            Write-Host "  '$u' - did you mean: $($suggestions -join ', ')?"
        }
        else {
            Write-Host "  '$u' - no close matches found"
        }
    }
    Write-Host ""
    Write-Host "Run with -ListJobs to see all selectable job names. Nothing was changed."
    exit 1
}

# Keep the master's job ordering rather than the user's input ordering.
$selectedOrdered = $availableJobNames | Where-Object { $resolvedNames -contains $_ }

$mcRemoved = @()
$outputLines = New-Object System.Collections.Generic.List[string]
$outputLines.AddRange([string[]]$parsedMaster.Preamble)

foreach ($stage in $parsedMaster.Stages) {
    if ($stage.Name -eq 'Test') {
        $outputLines.AddRange([string[]]$testParsed.Header)
        foreach ($jobName in $selectedOrdered) {
            $jobLines = $testParsed.Jobs[$jobName]
            if ($jobName -eq 'MergeCoverage') {
                $trimmed = Get-TrimmedMergeCoverageLines -JobLines $jobLines -SelectedJobs $selectedOrdered
                $jobLines = $trimmed.Lines
                $mcRemoved = $trimmed.Removed
            }
            $outputLines.AddRange([string[]]$jobLines)
        }
    }
    else {
        $outputLines.AddRange([string[]]$stage.Lines)
    }
}

if ($mcRemoved.Count -gt 0) {
    Write-Warning "MergeCoverage's dependsOn was trimmed to only the selected jobs (removed: $($mcRemoved -join ', ')). Coverage thresholds will only reflect the jobs you selected, not the full suite."
}

$generatedHeader = @(
    "# ============================================================================"
    "# GENERATED by Dev\.azure\Set-PipelineJobs.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"
    "# Test-stage jobs included: $($selectedOrdered -join ', ')"
    "# Source (canonical) ref:   $MasterRef"
    "#"
    "# To restore the previous pipeline.yml:  Dev\.azure\Set-PipelineJobs.ps1 -Restore"
    "# To list selectable jobs again:         Dev\.azure\Set-PipelineJobs.ps1 -ListJobs"
    "# ============================================================================"
    ""
)

$finalLines = @($generatedHeader) + @($outputLines.ToArray())
$finalContent = ($finalLines -join $Newline) + $Newline

if ($DryRun) {
    Write-Host $finalContent
    Write-Host "-- DryRun: nothing was written --"
    return
}

if (-not $Force) {
    Write-Host "This will overwrite Dev\.azure\pipeline.yml to run only: $($selectedOrdered -join ', ')"
    $confirmation = Read-Host "Continue? (y/N)"
    if ($confirmation -notin @('y', 'Y', 'yes', 'Yes')) {
        Write-Host "Aborted. Nothing was changed."
        return
    }
}

Backup-CurrentPipeline -Reason 'pre-generate' | Out-Null
[System.IO.File]::WriteAllText($PipelinePath, $finalContent, [System.Text.UTF8Encoding]::new($false))

Write-Host "pipeline.yml updated. Test stage now only runs: $($selectedOrdered -join ', ')"
Write-Host "Restore the previous pipeline.yml with: Dev\.azure\Set-PipelineJobs.ps1 -Restore"
