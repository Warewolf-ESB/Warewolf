using System;

namespace Warewolf.Execution.ServiceBusWorker.E2EHarness;

/// <summary>
/// Placeholder expansion for <c>--workflow-inputs-json</c>.
/// <para>
/// A load run publishes N messages that differ only by correlationId; without expansion every
/// message carries a byte-identical <c>inputs</c> map. That is not merely a weaker test — it
/// actively breaks workflows that key off the message body. <c>RabbitProcess.bite</c> calls
/// <c>dbo.usp_jobs1_LogStart</c>, which hashes the message content and takes an EXCLUSIVE
/// <c>sp_getapplock</c> on that hash for the life of its transaction (15s timeout). Identical
/// bodies therefore hash identically, so all N executions serialise behind a single lock and
/// are recorded as N retry *attempts of one job* rather than N distinct jobs.
/// </para>
/// <para>
/// Expanding <c>{correlationId}</c> into each message's own inputs gives every message a
/// distinct body, hence a distinct hash, hence genuine concurrency.
/// </para>
/// </summary>
internal static class WorkflowInputTemplate
{
    /// <summary>The original placeholder. Case-sensitive, matching the JSON field name.</summary>
    internal const string CorrelationIdPlaceholder = "{correlationId}";

    /// <summary>
    /// Emits the message's correlationId reformatted as a valid <c>uniqueidentifier</c>.
    /// <para>
    /// WOLF-8512: <c>profiler/ProfilerMain</c> keys on <c>MandateId</c>, a SQL
    /// <c>uniqueidentifier</c>, so <see cref="CorrelationIdPlaceholder"/> cannot be used there -
    /// a correlationId is 39 characters (<c>&lt;32-hex&gt;-&lt;6-digit&gt;</c>) and will not parse
    /// as a GUID. Without a per-message key in a column that reaches the database there is nothing
    /// to reconcile against, which is why Phase 4c could verify RabbitProcess per-message but not
    /// ProfilerMain.
    /// </para>
    /// <para>
    /// The emitted GUID is unique per message <b>and</b> per run: it takes the first 26 hex
    /// characters of the run's own correlationId prefix and the 6-digit message sequence. Run
    /// uniqueness is not cosmetic - <c>Profiler.usp_InsertProfilerRecommendation</c> is an upsert
    /// keyed on <c>(MandateId, ForPaymentCycle)</c>, so reusing MandateIds across runs would
    /// return <c>AlreadyExists=1</c>, insert nothing, and make a healthy second run look like
    /// 1000 lost messages.
    /// </para>
    /// </summary>
    internal const string CorrelationGuidPlaceholder = "{correlationGuid}";

    /// <summary>
    /// Replaces every <see cref="CorrelationIdPlaceholder"/> occurrence in <paramref name="workflowInputsJson"/>
    /// with <paramref name="correlationId"/>. Returns the input unchanged when it is null, empty,
    /// whitespace, or contains no placeholder — so callers that pass a literal inputs map keep
    /// their existing behaviour exactly.
    /// </summary>
    /// <remarks>
    /// Substitution happens on the raw JSON text *before* deserialisation, so a placeholder may
    /// appear in a value, inside a larger string, or multiple times. correlationIds are generated
    /// by the harness as GUID-derived hex plus an index suffix, so they contain no JSON
    /// metacharacters and cannot break the surrounding document.
    /// </remarks>
    internal static string Expand(string workflowInputsJson, string correlationId)
    {
        if (string.IsNullOrWhiteSpace(workflowInputsJson))
        {
            return workflowInputsJson;
        }
        return workflowInputsJson
            .Replace(CorrelationIdPlaceholder, correlationId ?? string.Empty)
            .Replace(CorrelationGuidPlaceholder, ToCorrelationGuid(correlationId));
    }

    /// <summary>
    /// Reformats <paramref name="correlationId"/> (<c>&lt;32-hex prefix&gt;-&lt;6-digit sequence&gt;</c>,
    /// as generated by the harness) into dashed GUID form, preserving both run identity and the
    /// message sequence: 26 hex characters of the prefix followed by the 6 sequence digits, which
    /// are themselves valid hex.
    /// </summary>
    /// <remarks>
    /// Defensive about shapes the harness does not currently produce, because the value is
    /// interpolated straight into a workflow input that SQL Server will parse: a single-message
    /// run has no <c>-NNNNNN</c> suffix, so the sequence falls back to <c>000000</c>, and anything
    /// that cannot yield 32 hex characters is padded deterministically rather than emitting a
    /// malformed GUID. Returns the all-zero GUID for a null/blank correlationId.
    /// </remarks>
    internal static string ToCorrelationGuid(string? correlationId)
    {
        if (string.IsNullOrWhiteSpace(correlationId))
        {
            return "00000000-0000-0000-0000-000000000000";
        }

        var separator = correlationId.LastIndexOf('-');
        var prefix   = separator >= 0 ? correlationId[..separator] : correlationId;
        var sequence = separator >= 0 ? correlationId[(separator + 1)..] : "000000";

        // Keep only hex characters; the sequence is decimal digits, which are already valid hex.
        prefix   = Keep32Hex(prefix);
        sequence = Keep32Hex(sequence);
        if (sequence.Length > 6)
        {
            sequence = sequence[^6..];
        }
        sequence = sequence.PadLeft(6, '0');

        var head = prefix.Length >= 26 ? prefix[..26] : prefix.PadRight(26, '0');
        var hex  = head + sequence;

        return $"{hex[..8]}-{hex[8..12]}-{hex[12..16]}-{hex[16..20]}-{hex[20..32]}";
    }

    static string Keep32Hex(string value)
    {
        var chars = new char[value.Length];
        var n = 0;
        foreach (var c in value)
        {
            if (Uri.IsHexDigit(c))
            {
                chars[n++] = c;
            }
        }
        return new string(chars, 0, n);
    }

    /// <summary>
    /// True when <paramref name="workflowInputsJson"/> contains the correlationId placeholder —
    /// i.e. each published message will carry a distinct inputs map.
    /// </summary>
    internal static bool HasCorrelationIdPlaceholder(string workflowInputsJson) =>
        !string.IsNullOrWhiteSpace(workflowInputsJson)
        && (workflowInputsJson.Contains(CorrelationIdPlaceholder, StringComparison.Ordinal)
            || workflowInputsJson.Contains(CorrelationGuidPlaceholder, StringComparison.Ordinal));
}
