"""Generates a natural-language goal per corpus workflow with the Claude CLI (System 1 eval/training input).

Reads the extractor's workflows.jsonl, summarises each workflow from its .bite (name, comment, inputs,
outputs, step labels) and asks Claude, 20 at a time, for the request a user would type to get it.
Appends to goals.jsonl and skips ids already there, so an interrupted run resumes where it stopped.

    python -I generate_goals.py <derivedDir> [--batch 20] [--limit N]

Run it from a directory with no CLAUDE.md: each call has no tools, no MCP servers and no settings.
"""

import argparse
import html
import json
import os
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

SYSTEM_PROMPT = """You are given summaries of Warewolf workflows. For each one, write the request a business user \
would type to ask for that workflow to be built: one or two plain sentences describing what it should do and \
with what inputs and outputs. Do not name Warewolf tools or activities (Assign, Decision, Switch, Sequence, \
For Each, Data Split, Data Merge, Replace, Comment, SQL Server Database, Web Method, Service, and so on) and do \
not describe the steps one by one; describe the outcome. Reply with one JSON object per line and nothing else: \
{"id": "<id>", "goal": "<goal>"}"""

CLAUDE = shutil.which("claude") or "claude"
GENERATED_COMMENT = re.compile(r"^Generated by", re.IGNORECASE)
MAX_STEPS = 40


def summarise(workflow):
    root = ET.parse(workflow["file"]).getroot()
    comment = (root.findtext("Comment") or "").strip()
    inputs, outputs = [], []
    data_list = root.find("DataList")
    for column in data_list if data_list is not None else []:
        direction = column.get("ColumnIODirection", "")
        if direction in ("Input", "Both"):
            inputs.append(column.tag)
        if direction in ("Output", "Both"):
            outputs.append(column.tag)

    labels = []
    xaml = root.findtext("Action/XamlDefinition") or ""
    try:
        for element in ET.fromstring(html.unescape(xaml) if xaml.lstrip().startswith("&lt;") else xaml).iter():
            label = element.get("DisplayName")
            tag = element.tag.rsplit("}", 1)[-1]
            if label and tag not in ("Activity", "Flowchart"):
                labels.append(label.strip())
    except ET.ParseError:
        pass

    lines = [f"id: {workflow['id']}", f"name: {workflow['name']}"]
    if comment and not GENERATED_COMMENT.match(comment):
        lines.append(f"comment: {comment[:400]}")
    lines.append(f"inputs: {', '.join(inputs) or '(none)'}")
    lines.append(f"outputs: {', '.join(outputs) or '(none)'}")
    lines.append(f"steps: {' | '.join(labels[:MAX_STEPS])}{' | ...' if len(labels) > MAX_STEPS else ''}")
    return "\n".join(lines)


def ask_claude(summaries):
    prompt = "\n\n".join(summaries)
    # No shell: on Windows cmd.exe would read the prompt's "<id>" as an input redirection.
    result = subprocess.run(
        [CLAUDE, "-p", "--model", "sonnet", "--tools", "", "--strict-mcp-config", "--setting-sources", "",
         "--no-session-persistence", "--system-prompt", SYSTEM_PROMPT],
        input=prompt, capture_output=True, text=True, encoding="utf-8", timeout=600)
    if result.returncode != 0:
        raise RuntimeError(f"claude exited {result.returncode}: {result.stderr.strip()[:500]}")
    goals = {}
    for line in result.stdout.splitlines():
        line = line.strip()
        if line.startswith("{"):
            try:
                row = json.loads(line)
                goals[row["id"]] = row["goal"].strip()
            except (json.JSONDecodeError, KeyError, AttributeError):
                pass
    return goals


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("derived")
    parser.add_argument("--batch", type=int, default=20)
    parser.add_argument("--limit", type=int, default=0, help="stop after this many workflows (0 = all)")
    args = parser.parse_args()

    workflows_path = os.path.join(args.derived, "workflows.jsonl")
    goals_path = os.path.join(args.derived, "goals.jsonl")
    with open(workflows_path, encoding="utf-8") as f:
        workflows = [w for w in map(json.loads, f) if not w.get("error")]

    done = set()
    if os.path.exists(goals_path):
        with open(goals_path, encoding="utf-8") as f:
            done = {json.loads(line)["id"] for line in f if line.strip()}

    pending = [w for w in workflows if w["id"] not in done]
    if args.limit:
        pending = pending[:args.limit]
    print(f"{len(workflows)} workflows, {len(done)} already have goals, {len(pending)} to do", flush=True)

    written = missed = 0
    with open(goals_path, "a", encoding="utf-8") as out:
        for start in range(0, len(pending), args.batch):
            batch = pending[start:start + args.batch]
            by_id = {w["id"]: w for w in batch}
            try:
                goals = ask_claude([summarise(w) for w in batch])
            except Exception as error:  # one bad batch must not lose the rest; a re-run retries it
                print(f"batch {start // args.batch + 1}: {error}", file=sys.stderr, flush=True)
                missed += len(batch)
                continue
            for workflow_id, goal in goals.items():
                if workflow_id in by_id and goal:
                    w = by_id[workflow_id]
                    out.write(json.dumps({"id": workflow_id, "set": w["set"], "name": w["name"], "goal": goal}) + "\n")
                    written += 1
            out.flush()
            missed += len(batch) - len([i for i in goals if i in by_id])
            print(f"batch {start // args.batch + 1}: {written} written, {missed} missed", flush=True)

    print(f"done: {written} written, {missed} missed (re-run to retry missed ones)")


if __name__ == "__main__":
    main()
